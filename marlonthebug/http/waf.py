@dataclass
class WAFDetection:
    detected: bool
    name: str = ""
    confidence: float = 0.0
    evidence: list[str] = field(default_factory=list)


class WAFFingerprinter:
    def __init__(self) -> None:
        self._signatures = WAF_SIGNATURES

    def detect(
        self,
        status_code: int,
        headers: dict[str, str],
        body: str,
        cookies: dict[str, str] | None = None,
    ) -> WAFDetection:
        best_match: WAFDetection = WAFDetection(detected=False)
        cookies = cookies or {}

        for sig in self._signatures:
            score = 0
            evidence: list[str] = []

            for header_name in sig.get("headers", {}):
                if any(h.lower() == header_name.lower() for h in headers):
                    score += 3
                    evidence.append(f"Header: {header_name}")

            for cookie_name in sig.get("cookies", {}):
                if any(c.lower().startswith(cookie_name.lower()) for c in cookies):
                    score += 3
                    evidence.append(f"Cookie: {cookie_name}")

            if status_code in sig.get("response_codes", []):
                score += 1
                evidence.append(f"Status: {status_code}")

            body_lower = body.lower()
            for keyword in sig.get("response_body", []):
                if keyword in body_lower:
                    score += 4
                    evidence.append(f"Body: {keyword}")

            if evidence:
                confidence = min(score / 10.0, 1.0)
                if confidence > best_match.confidence:
                    best_match = WAFDetection(
                        detected=True,
                        name=sig["name"],
                        confidence=confidence,
                        evidence=evidence,
                    )

        return best_match

    def is_waf_block(self, status_code: int, body: str) -> bool:
        block_indicators = [
            "blocked",
            "access denied",
            "request rejected",
            "forbidden",
            "not authorized",
            "captcha",
            "security check",
            "challenge",
            "javascript required",
        ]
        body_lower = body.lower()
        if status_code in (403, 401, 429, 503):
            return True
        return any(indicator in body_lower for indicator in block_indicators)
